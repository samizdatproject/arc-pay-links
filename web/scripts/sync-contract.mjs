// Copies the ABI and creation bytecode from the Foundry build into src/contract.ts.
// Run after `forge build` in ../contracts:  node scripts/sync-contract.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const art = JSON.parse(
  readFileSync(fileURLToPath(new URL('../../contracts/out/ArcPayLinks.sol/ArcPayLinks.json', import.meta.url)), 'utf8'),
);
const out = `// Generated by scripts/sync-contract.mjs from contracts/out. Do not edit by hand.
export const arcPayLinksAbi = ${JSON.stringify(art.abi, null, 2)} as const;

export const arcPayLinksBytecode = '${art.bytecode.object}' as const;
`;
writeFileSync(fileURLToPath(new URL('../src/contract.ts', import.meta.url)), out);
console.log('wrote src/contract.ts');
